func GetSqlite() (*public.Sqlite, error) {
	s, err := public.NewSqlite("data/data.db", "")
	if err != nil {
		return nil, err
	}
	s.TableName = "cert"
	return s, nil
}

// getWorkflowsBySha256s returns all workflows, used to compute workflow_refs per cert.
func getWorkflowsBySha256s() ([]map[string]any, error) {
	s, err := public.NewSqlite("data/data.db", "")
	if err != nil {
		return nil, err
	}
	s.TableName = "workflow"
	defer s.Close()
	return s.Where("1=1", []interface{}{}).Select()
}

func GetList(search string, p, limit, status int64) ([]map[string]any, int, error) {
	var data []map[string]any
	var count int64
	s, err := GetSqlite()
	if err != nil {
		return data, 0, err
	}
	defer s.Close()

	var limits []int64
	if p >= 0 && limit >= 0 {
		limits = []int64{0, limit}
		if p > 1 {
			limits[0] = (p - 1) * limit
			limits[1] = limit
		}
	}

	// 获取当前时间
	now := time.Now()
	// 转换为字符串格式
	nowStr := now.Format("2006-01-02 15:04:05")
	// 30 天后的时间
	nowPlus30Days := now.AddDate(0, 0, 30)
	nowPlus30DaysStr := nowPlus30Days.Format("2006-01-02 15:04:05")

	filterSql := "1=1 "
	// status: -1 已过期 0/其它 全部 1 即将过期 2 正常
	if status == -1 {
		filterSql += "and end_time <= '" + nowStr + "'"
	} else if status == 1 {
		filterSql += "and end_time > '" + nowStr + "' AND end_time <= '" + nowPlus30DaysStr + "'"
	} else if status == 2 {
		filterSql += "and end_time > '" + nowPlus30DaysStr + "'"
	}

	if search != "" {
		filterSql += "and domains like '%" + search + "%'"
	}
	count, err = s.Where(filterSql, []interface{}{}).Count()
	data, err = s.Where(filterSql, []interface{}{}).Order("end_time", "esc").Limit(limits).Select()

	if err != nil {
		return data, 0, err
	}
	for _, v := range data {
		endtime, err := time.Parse("2006-01-02 15:04:05", v["end_time"].(string))
		if err != nil {
			continue
		}
		v["end_day"] = strconv.FormatInt(int64(endtime.Sub(time.Now())/(24*time.Hour)), 10)
	}

	// For workflow_id matching, only the cert with the highest id per workflow
	// is considered actively associated; older certs generated by the same
	// workflow are historical and no longer in use.
	latestCertForWorkflow := map[string]int64{}
	if sc, err2 := GetSqlite(); err2 == nil {
		if all, err3 := sc.Field([]string{"id", "workflow_id"}).Where("workflow_id != '' AND workflow_id != 'null'", []interface{}{}).Select(); err3 == nil {
			for _, c := range all {
				wfid := fmt.Sprintf("%v", c["workflow_id"])
				if wfid == "" || wfid == "<nil>" {
					continue
				}
				var cid int64
				switch v := c["id"].(type) {
				case int64:
					cid = v
				case int:
					cid = int64(v)
				}
				if prev, ok := latestCertForWorkflow[wfid]; !ok || cid > prev {
					latestCertForWorkflow[wfid] = cid
				}
			}
		}
		sc.Close()
	}

	// Attach workflow_refs to each cert
	workflows, _ := getWorkflowsBySha256s()
	for i, c := range data {
		sha, _ := c["sha256"].(string)
		wfId := fmt.Sprintf("%v", c["workflow_id"])
		var certId int64
		switch v := c["id"].(type) {
		case int64:
			certId = v
		case int:
			certId = int64(v)
		}
		var refs []map[string]string
		seen := map[string]bool{}
		for _, w := range workflows {
			wid := fmt.Sprintf("%v", w["id"])
			wname, _ := w["name"].(string)
			wcontent, _ := w["content"].(string)
			if seen[wid] {
				continue
			}
			isLatestForWorkflow := wfId != "" && wfId != "<nil>" && wfId == wid && certId == latestCertForWorkflow[wfId]
			if isLatestForWorkflow || (sha != "" && strings.Contains(wcontent, sha)) {
				refs = append(refs, map[string]string{"id": wid, "name": wname})
				seen[wid] = true
			}
		}
		if refs == nil {
			refs = []map[string]string{}
		}
		data[i]["workflow_refs"] = refs
	}

	return data, int(count), nil
}

func AddCert(source, key, cert, issuer, issuerCert, domains, sha256, historyId, startTime, endTime, endDay string) error {
	s, err := GetSqlite()
	if err != nil {
		return err
	}
	defer s.Close()
	workflowId := ""
	if historyId != "" {
		s, err := public.NewSqlite("data/data.db", "")
		if err != nil {
			return err
		}
		s.TableName = "workflow_history"
		defer s.Close()
		// 查询 workflowId
		wh, err := s.Where("id=?", []interface{}{historyId}).Select()
		if err != nil {
			return err
		}
		if len(wh) > 0 {
			workflowId = wh[0]["workflow_id"].(string)
		}
	}

	now := time.Now().Format("2006-01-02 15:04:05")
	_, err = s.Insert(map[string]any{
		"source":      source,
		"key":         key,
		"cert":        cert,
		"issuer":      issuer,
		"issuer_cert": issuerCert,
		"domains":     domains,
		"sha256":      sha256,
		"history_id":  historyId,
		"workflow_id": workflowId,
		"create_time": now,
		"update_time": now,
		"start_time":  startTime,
		"end_time":    endTime,
		"end_day":     endDay,
	})
	if err != nil {
		return err
	}
	return nil
}

func SaveCert(source, key, cert, issuerCert, historyId string) (string, error) {
	if err := public.ValidateSSLCertificate(cert, key); err != nil {
		return "", err
	}

	certObj, err := public.ParseCertificate([]byte(cert))
	if err != nil {
		return "", fmt.Errorf("解析证书失败: %v", err)
	}
	// SHA256
	sha256, err := public.GetSHA256(cert)
	if err != nil {
		return "", fmt.Errorf("获取 SHA256 失败: %v", err)
	}
	// 先校验再去重：库里已有的旧证书重新上传也要经过同样的规则
	identifiers := public.ExtractCertDomains(certObj)
	if err := checkIdentifiersStorable(identifiers); err != nil {
		return "", err
	}
	if d, _ := GetCert(sha256); d != nil {
		return sha256, nil
	}
	domainList := strings.Join(identifiers, ",")

	// 提取 CA 名称（Issuer 的组织名）
	caName := "UNKNOWN"
	if len(certObj.Issuer.Organization) > 0 {
		caName = certObj.Issuer.Organization[0]
	} else if certObj.Issuer.CommonName != "" {
		caName = certObj.Issuer.CommonName
	}
	// 证书有效期
	startTime := certObj.NotBefore.Format("2006-01-02 15:04:05")
	endTime := certObj.NotAfter.Format("2006-01-02 15:04:05")
	endDay := fmt.Sprintf("%d", int(certObj.NotAfter.Sub(time.Now()).Hours()/24))

	err = AddCert(source, key, cert, caName, issuerCert, domainList, sha256, historyId, startTime, endTime, endDay)
	if err != nil {
		return "", fmt.Errorf("保存证书失败: %v", err)
	}
	return sha256, nil
}

// checkIdentifiersStorable 校验证书标识能否以逗号连接存储。证书的 domains 列和上传节点的匹配条件都是
// 逗号连接的，标识本身含逗号（合法的 DNS 名称和 IP 都不会）会被拆成多个，导致匹配条件错误。
// 上传与编辑共用这条规则。
func checkIdentifiersStorable(identifiers []string) error {
	for _, d := range identifiers {
		if strings.Contains(d, ",") {
			return fmt.Errorf("证书标识「%s」包含逗号，不是合法的域名或 IP，无法保存", d)
		}
	}
	return nil
}

// UpdateCert 更新一张手动上传（source=="upload"）的证书。
// 契约：返回 len(uncovered) > 0 且 err == nil 时，表示新证书域名未覆盖原证书域名，
// 证书「未写库」，需用户确认后带 force=true 重试；此时 newSha256 为空。
// 证书更新与关联工作流同步（sha256 替换、上传节点匹配域名）在同一个 BEGIN IMMEDIATE 事务内完成，
// 任一步失败整体回滚；并发编辑会在写锁上排队，不会互相覆盖。
func UpdateCert(id, certPEM, keyPEM string, force bool) (oldSha256, newSha256 string, uncovered []string, err error) {
	if err = public.ValidateSSLCertificate(certPEM, keyPEM); err != nil {
		return
	}
	certObj, err := public.ParseCertificate([]byte(certPEM))
	if err != nil {
		err = fmt.Errorf("解析证书失败: %v", err)
		return
	}
	newSha256, err = public.GetSHA256(certPEM)
	if err != nil {
		err = fmt.Errorf("获取 SHA256 失败: %v", err)
		return
	}
	// 解析新证书元数据
	// 去掉空白条目（证书可带空的 DNS SAN）。没有任何域名的证书（如只有 URI SAN 的客户端证书）仍允许编辑，
	// 但若有开启本地匹配的上传节点引用它，同步时会报错回滚（见 planUploadNode，标识含逗号时同理）。
	var domains []string
	for _, d := range public.ExtractCertDomains(certObj) {
		if strings.TrimSpace(d) != "" {
			domains = append(domains, d)
		}
	}
	if err = checkIdentifiersStorable(domains); err != nil {
		return
	}

	s, err := GetSqlite()
	if err != nil {
		return
	}
	defer s.Close()
	ctx := context.Background()
	conn, err := s.Conn.Conn(ctx)
	if err != nil {
		return
	}
	defer conn.Close()
	// 开始即获取写锁，读取旧记录、校验、写证书、同步工作流都在锁内完成
	if _, err = conn.ExecContext(ctx, "BEGIN IMMEDIATE"); err != nil {
		return
	}
	committed := false
	defer func() {
		if !committed {
			conn.ExecContext(ctx, "ROLLBACK")
		}
	}()

	// 读取当前记录，校验 source 必须为 upload
	var (
		dbID                                int64
		source, oldSha, oldCertPEM, oldDoms sql.NullString
	)
	err = conn.QueryRowContext(ctx, "SELECT id, source, sha256, cert, domains FROM cert WHERE id=?", id).
		Scan(&dbID, &source, &oldSha, &oldCertPEM, &oldDoms)
	if err != nil {
		err = fmt.Errorf("证书不存在")
		return
	}
	if source.String != "upload" {
		err = fmt.Errorf("仅支持编辑手动上传的证书")
		return
	}
	oldSha256 = oldSha.String

	// 校验新证书域名是否覆盖原证书域名，未覆盖且未强制时提前返回（不做任何变更）。
	// 以重新解析旧证书 PEM 为准（真源），而非信任去规范化的 domains 缓存列；
	// 仅当旧证书缺失/解析失败时才回退到缓存列。
	if !force {
		var oldDomains []string
		if oldCertPEM.String != "" {
			if oldObj, e := public.ParseCertificate([]byte(oldCertPEM.String)); e == nil {
				oldDomains = public.ExtractCertDomains(oldObj)
			}
		}
		if oldDomains == nil {
			oldDomains = strings.Split(oldDoms.String, ",")
		}
		uncovered = public.UncoveredDomains(domains, oldDomains)
		if len(uncovered) > 0 {
			newSha256 = "" // 未写库，不返回 sha（契约见函数注释）
			return
		}
	}

	caName := "UNKNOWN"
	if len(certObj.Issuer.Organization) > 0 {
		caName = certObj.Issuer.Organization[0]
	} else if certObj.Issuer.CommonName != "" {
		caName = certObj.Issuer.CommonName
	}

	now := time.Now().Format("2006-01-02 15:04:05")
	newDomains := strings.Join(domains, ",")
	_, err = conn.ExecContext(ctx,
		"UPDATE cert SET cert=?, key=?, sha256=?, domains=?, issuer=?, start_time=?, end_time=?, end_day=?, update_time=? WHERE id=?",
		certPEM, keyPEM, newSha256, newDomains, caName,
		certObj.NotBefore.Format("2006-01-02 15:04:05"),
		certObj.NotAfter.Format("2006-01-02 15:04:05"),
		fmt.Sprintf("%d", int(certObj.NotAfter.Sub(time.Now()).Hours()/24)),
		now, dbID)
	if err != nil {
		return
	}

	// 把所有 workflow content 中的旧 sha256 替换为新 sha256，
	// 并同步引用该证书的上传节点保存的匹配域名（临期时按它查找本地替代证书）。
	if err = syncCertRefsInWorkflows(ctx, conn, oldSha256, newSha256, dbID, domains); err != nil {
		err = fmt.Errorf("同步关联工作流失败，证书未更新: %v", err)
		return
	}
	if _, err = conn.ExecContext(ctx, "COMMIT"); err != nil {
		return
	}
	committed = true
	return
}

// ExecNode 与 workflow.WorkflowNode 的 JSON 字段完全一致，用来按执行器（RunWorkflow 的 json.Unmarshal）
// 同样的方式解码工作流。cert 包不能导入 workflow（workflow 依赖 cert），一致性由 cert_exec_node_test.go 校验。
type ExecNode struct {
	Id     string           `json:"id"`
	Type   string           `json:"type"`
	Name   string           `json:"name"`
	Config map[string]any   `json:"config"`
	Inputs []ExecNodeParams `json:"inputs"`

	ChildNode      *ExecNode   `json:"childNode,omitempty"`
	ConditionNodes []*ExecNode `json:"conditionNodes,omitempty"`

	Validated bool `json:"validated"`
}

// ExecNodeParams 对应 workflow.WorkflowNodeParams。
type ExecNodeParams struct {
	Name       string `json:"name"`
	FromNodeID string `json:"fromNodeId,omitempty"`
}

// errUnsafeRewrite 表示重写后的工作流按执行器解码与预期不一致（如存在重复或仅大小写不同的字段），不能写回。
var errUnsafeRewrite = errors.New("工作流结构无法安全地自动更新，请在工作流里重新选择该证书后再编辑")

// certRefMatcher 判断上传节点的 cert_id 是否指向正在编辑的证书（数据库 id 为 dbID、更新后 sha256 为 sha）。
//   - 等于新 sha256 直接视为匹配：sha256 不唯一时执行器可能取到另一行，但同一 sha256 意味着证书内容与域名相同。
//   - 其他文本只与被编辑的那一行按主键比较 "? = id"：绑定参数无亲和性，SQLite 会对它应用数值亲和，
//     与执行时 GetCert 的 "id=?" 规则一致（"007"、" 7"、"7.0" 等都等于 7），且不扫表。
//
// 查询出错时记录到 err，由调用方回滚，不能当作不匹配处理。
type certRefMatcher struct {
	ctx   context.Context
	conn  *sql.Conn
	dbID  int64
	sha   string
	cache map[string]bool
	err   error
}

// sqliteNumericTextRe 是 SQLite 数值亲和可能转换的文本的超集（ASCII 空白、符号、十进制、小数、指数）。
// 只用于预筛，是否相等仍由 SQLite 判断。
var sqliteNumericTextRe = regexp.MustCompile(`^[ \t\n\v\f\r]*[+-]?(\d+\.?\d*|\.\d+)([eE][+-]?\d+)?[ \t\n\v\f\r]*$`)

func newCertRefMatcher(ctx context.Context, conn *sql.Conn, dbID int64, sha string) *certRefMatcher {
	return &certRefMatcher{ctx: ctx, conn: conn, dbID: dbID, sha: sha, cache: map[string]bool{}}
}

func (m *certRefMatcher) match(certID string) bool {
	if m.err != nil {
		return false
	}
	if certID == m.sha {
		return true
	}
	if v, ok := m.cache[certID]; ok {
		return v
	}
	// 不可能被 SQLite 按数值亲和转换的文本（如其他证书的 sha256）一定不等于整数 id，免去写锁内的查询
	if !sqliteNumericTextRe.MatchString(certID) {
		return false
	}
	var eq sql.NullBool
	err := m.conn.QueryRowContext(m.ctx, "SELECT ? = id FROM cert WHERE id=?", certID, m.dbID).Scan(&eq)
	if err != nil && !errors.Is(err, sql.ErrNoRows) {
		m.err = err
		return false
	}
	m.cache[certID] = err == nil && eq.Valid && eq.Bool
	return m.cache[certID]
}

// execCertID 把 cert_id 按执行器 upload() 的规则转成查询参数；不是数字或字符串时执行器会报错，返回 false。
func execCertID(v any) (string, bool) {
	switch id := v.(type) {
	case float64:
		return strconv.Itoa(int(id)), true
	case json.Number:
		f, err := id.Float64()
		if err != nil {
			return "", false
		}
		return strconv.Itoa(int(f)), true
	case string:
		return id, true
	}
	return "", false
}

// certChange 描述一次证书编辑对工作流的影响。
type certChange struct {
	oldSha  string            // 编辑前的 sha256
	newSha  string            // 编辑后的 sha256
	domains string            // 新证书域名，逗号连接（上传节点 domains 的存储格式）
	usable  bool              // domains 能否作为本地匹配条件：为空或某个标识本身含逗号时不能
	isRef   func(string) bool // cert_id（按执行器规则转成的文本）是否指向被编辑的证书
}

// newCertChange 根据新证书的标识列表构造 certChange。
func newCertChange(oldSha, newSha string, domains []string, isRef func(string) bool) certChange {
	usable := len(domains) > 0
	for _, d := range domains {
		if strings.Contains(d, ",") {
			usable = false
		}
	}
	return certChange{oldSha: oldSha, newSha: newSha, domains: strings.Join(domains, ","), usable: usable, isRef: isRef}
}

// rewriteWorkflowContent 计算证书编辑后的工作流内容；无变化时原样返回。
// 执行器能解码的工作流交给 syncUploadNodes 在解码后的 JSON 上处理（sha256 替换与上传节点同步）；
// 直接在原文上替换可能命中转义序列（如 \u0031 后紧跟旧 sha 的其余部分）而改坏引用。
// 执行器解码不了的内容本来就不会被执行，沿用原来的纯文本替换。
func rewriteWorkflowContent(content string, ch certChange) (string, error) {
	out, changed, err := syncUploadNodes(content, ch)
	if errors.Is(err, errNotExecutable) {
		if ch.oldSha != "" && ch.oldSha != ch.newSha {
			return strings.ReplaceAll(content, ch.oldSha, ch.newSha), nil
		}
		return content, nil
	}
	if err != nil {
		return content, err
	}
	if changed {
		return out, nil
	}
	return content, nil
}

// syncCertRefsInWorkflows 在调用方的事务连接上把证书变更同步到所有工作流，任一失败即返回错误。
func syncCertRefsInWorkflows(ctx context.Context, conn *sql.Conn, oldSha256, newSha256 string, dbID int64, domains []string) error {
	matcher := newCertRefMatcher(ctx, conn, dbID, newSha256)
	ch := newCertChange(oldSha256, newSha256, domains, matcher.match)
	rows, err := conn.QueryContext(ctx, "SELECT id, name, content FROM workflow")
	if err != nil {
		return err
	}
	type wf struct {
		id            any
		name, content sql.NullString
	}
	var ws []wf
	for rows.Next() {
		var w wf
		if err := rows.Scan(&w.id, &w.name, &w.content); err != nil {
			rows.Close()
			return err
		}
		ws = append(ws, w)
	}
	if err := rows.Err(); err != nil {
		rows.Close()
		return err
	}
	rows.Close()
	for _, w := range ws {
		newContent, err := rewriteWorkflowContent(w.content.String, ch)
		if err == nil && matcher.err != nil {
			err = matcher.err
		}
		if err != nil {
			return fmt.Errorf("工作流「%s」: %v", w.name.String, err)
		}
		if newContent == w.content.String {
			continue
		}
		if _, err := conn.ExecContext(ctx, "UPDATE workflow SET content=? WHERE id=?", newContent, w.id); err != nil {
			return fmt.Errorf("工作流「%s」: %v", w.name.String, err)
		}
	}
	return nil
}

// errDomainsUnusableForLocalMatch 表示新证书的域名无法作为本地匹配条件，但有开启本地匹配的上传节点引用它。
var errDomainsUnusableForLocalMatch = errors.New("新证书没有可用于本地匹配的域名（为空或包含逗号），而该工作流的上传节点开启了「从本地获取符合条件的证书」，请先关闭该选项或更换证书")

// hexCharEscapeRe 匹配能写出十六进制字符（0-9、A-F、a-f）的 JSON \u 转义。
var hexCharEscapeRe = regexp.MustCompile(`\\u00(3[0-9]|4[1-6]|6[1-6])`)

// errNotExecutable 表示内容无法按执行器的方式解码（执行器同样无法运行该工作流）。
var errNotExecutable = errors.New("工作流内容无法解析")

// replaceInJSONValue 把解码后 JSON 值里所有字符串（含对象键）中的 old 替换为 new，返回新值与是否有替换。
// 替换后对象键冲突（如同时有以旧、新 sha256 为键的两项）会丢数据，返回 errUnsafeRewrite。
func replaceInJSONValue(v any, old, new string) (any, bool, error) {
	switch val := v.(type) {
	case string:
		if strings.Contains(val, old) {
			return strings.ReplaceAll(val, old, new), true, nil
		}
		return val, false, nil
	case map[string]any:
		out := make(map[string]any, len(val))
		changed := false
		for k, item := range val {
			nk := k
			if strings.Contains(k, old) {
				nk, changed = strings.ReplaceAll(k, old, new), true
			}
			if _, dup := out[nk]; dup {
				return v, false, errUnsafeRewrite
			}
			nv, c, err := replaceInJSONValue(item, old, new)
			if err != nil {
				return v, false, err
			}
			changed = changed || c
			out[nk] = nv
		}
		return out, changed, nil
	case []any:
		out := make([]any, len(val))
		changed := false
		for i, item := range val {
			nv, c, err := replaceInJSONValue(item, old, new)
			if err != nil {
				return v, false, err
			}
			out[i] = nv
			changed = changed || c
		}
		return out, changed, nil
	}
	return v, false, nil
}

// replaceShaInExecTree 在执行树的所有字符串字段上做同样的替换，用于构造校验用的预期结果。
func replaceShaInExecTree(node *ExecNode, old, new string) (bool, error) {
	if node == nil {
		return false, nil
	}
	changed := false
	for _, f := range []*string{&node.Id, &node.Type, &node.Name} {
		if strings.Contains(*f, old) {
			*f, changed = strings.ReplaceAll(*f, old, new), true
		}
	}
	for i := range node.Inputs {
		for _, f := range []*string{&node.Inputs[i].Name, &node.Inputs[i].FromNodeID} {
			if strings.Contains(*f, old) {
				*f, changed = strings.ReplaceAll(*f, old, new), true
			}
		}
	}
	if node.Config != nil {
		cfg, c, err := replaceInJSONValue(node.Config, old, new)
		if err != nil {
			return false, err
		}
		if c {
			node.Config, changed = cfg.(map[string]any), true
		}
	}
	c, err := replaceShaInExecTree(node.ChildNode, old, new)
	if err != nil {
		return false, err
	}
	changed = changed || c
	for _, b := range node.ConditionNodes {
		c, err := replaceShaInExecTree(b, old, new)
		if err != nil {
			return false, err
		}
		changed = changed || c
	}
	return changed, nil
}

// decodeExecTree 按执行器的方式解码工作流；失败时执行器同样无法运行该工作流。
func decodeExecTree(content string) (*ExecNode, error) {
	var node ExecNode
	if err := json.Unmarshal([]byte(content), &node); err != nil {
		return nil, err
	}
	return &node, nil
}

// planUploadNode 按执行器 upload() 的语义判断一个上传节点的 config 需要怎样修改：
//   - cert_id 仍是旧 sha256（文本替换没覆盖到，如 JSON 转义写法）：改为新 sha256，否则引用会失效；
//   - 引用被编辑的证书：domains 改为新证书域名；新域名不能用于本地匹配时，开启 use_local_cert 的节点报错。
//
// apply 为 true 时直接修改 cfg。返回是否需要修改。
func planUploadNode(cfg map[string]any, ch certChange, apply bool) (bool, error) {
	id, ok := execCertID(cfg["cert_id"])
	if !ok {
		return false, nil
	}
	changed := false
	ref := false
	if ch.oldSha != "" && ch.oldSha != ch.newSha && id == ch.oldSha {
		if apply {
			cfg["cert_id"] = ch.newSha
		}
		changed, ref = true, true
	} else {
		ref = ch.isRef(id)
	}
	if !ref {
		return changed, nil
	}
	if !ch.usable {
		if useLocal, _ := cfg["use_local_cert"].(bool); useLocal {
			return false, errDomainsUnusableForLocalMatch
		}
		// 未开启本地匹配：清空旧证书的域名，避免以后开启时沿用过期的匹配条件（前端会因缺少域名拦截开启）
		if cur, _ := cfg["domains"].(string); cur != "" {
			if apply {
				cfg["domains"] = ""
			}
			changed = true
		}
		return changed, nil
	}
	if cur, _ := cfg["domains"].(string); !sameDomainSet(cur, ch.domains) {
		if apply {
			cfg["domains"] = ch.domains
		}
		changed = true
	}
	return changed, nil
}

// patchExecTree 在执行树上应用 planUploadNode。遍历 childNode 与全部 conditionNodes
// （执行器只会走其中一部分，多处理的节点不影响执行）。
func patchExecTree(node *ExecNode, ch certChange) (bool, error) {
	if node == nil {
		return false, nil
	}
	changed := false
	if node.Type == "upload" && node.Config != nil {
		c, err := planUploadNode(node.Config, ch, true)
		if err != nil {
			return false, err
		}
		changed = c
	}
	c, err := patchExecTree(node.ChildNode, ch)
	if err != nil {
		return false, err
	}
	changed = changed || c
	for _, b := range node.ConditionNodes {
		c, err := patchExecTree(b, ch)
		if err != nil {
			return false, err
		}
		changed = changed || c
	}
	return changed, nil
}

// syncUploadNodes 让工作流中的上传节点跟上证书编辑（见 planUploadNode）。
// 上传节点的 domains 由前端在选择证书时自动填入，开启 use_local_cert 后证书临期时按它查找替代证书；
// 手动证书被编辑后若不同步，会按旧域名匹配。
//
// 需要改哪些节点按执行器的解码方式（ExecNode）判断；实际改写在保留原字段的 JSON 上进行，写回前再按
// 执行器方式解码校验：结果必须与预期的执行树完全一致，否则返回 errUnsafeRewrite，由调用方回滚。
// content 本身不是合法工作流时执行器无法运行，原样返回。
func syncUploadNodes(content string, ch certChange) (string, bool, error) {
	expected, err := decodeExecTree(content)
	if err != nil {
		return content, false, errNotExecutable
	}
	// 原文既不含旧 sha256、也没有能写出十六进制字符的 \u 转义时，解码后的字符串不可能含旧 sha256，
	// 无需替换；这样与本证书无关的工作流在写锁内只解码一次。
	replaceSha := ch.oldSha != "" && ch.oldSha != ch.newSha &&
		(strings.Contains(content, ch.oldSha) || hexCharEscapeRe.MatchString(content))
	changed := false
	if replaceSha {
		if changed, err = replaceShaInExecTree(expected, ch.oldSha, ch.newSha); err != nil {
			return content, false, err
		}
	}
	patched, err := patchExecTree(expected, ch)
	if err != nil {
		return content, false, err
	}
	if !replaceSha && !patched {
		return content, false, nil
	}

	dec := json.NewDecoder(strings.NewReader(content))
	dec.UseNumber() // 保持数字原样，避免大整数被转成科学计数法
	var root any
	if err := dec.Decode(&root); err != nil {
		return content, false, errNotExecutable
	}
	if replaceSha {
		var c bool
		if root, c, err = replaceInJSONValue(root, ch.oldSha, ch.newSha); err != nil {
			return content, false, err
		}
		changed = changed || c
	}
	if !changed && !patched {
		return content, false, nil
	}
	// 只需替换 sha256 时优先沿用原来的原文替换（保留键顺序与格式）；仅当它与逐字符串替换等价时采用，
	// 否则（如旧 sha 与 \u 转义序列重叠）走下面的重新编码路径。
	if !patched {
		raw := strings.ReplaceAll(content, ch.oldSha, ch.newSha)
		rawDec := json.NewDecoder(strings.NewReader(raw))
		rawDec.UseNumber()
		var rawRoot any
		if rawDec.Decode(&rawRoot) == nil && reflect.DeepEqual(rawRoot, root) {
			if actual, err := decodeExecTree(raw); err == nil && reflect.DeepEqual(expected, actual) {
				return raw, raw != content, nil
			}
		}
	}

	// 沿 childNode / conditionNodes（字段名不区分大小写，与 encoding/json 一致）找到上传节点并改写；
	// 不进入 config，避免改到插件业务数据。
	var walk func(v any)
	walk = func(v any) {
		node, ok := v.(map[string]any)
		if !ok {
			return
		}
		var isUpload bool
		var configs []map[string]any
		var next []any
		for k, val := range node {
			switch {
			case strings.EqualFold(k, "type"):
				if t, _ := val.(string); t == "upload" {
					isUpload = true
				}
			case strings.EqualFold(k, "config"):
				if cfg, ok := val.(map[string]any); ok {
					configs = append(configs, cfg)
				}
			case strings.EqualFold(k, "childNode"):
				next = append(next, val)
			case strings.EqualFold(k, "conditionNodes"):
				if arr, ok := val.([]any); ok {
					next = append(next, arr...)
				}
			}
		}
		if isUpload {
			for _, cfg := range configs {
				planUploadNode(cfg, ch, true)
			}
		}
		for _, n := range next {
			walk(n)
		}
	}
	// 只有执行树确实需要修改上传节点时才改写；仅替换 sha256 时不动节点，避免误改被执行器视为其他类型的节点
	if patched {
		walk(root)
	}
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	if err := enc.Encode(root); err != nil {
		return content, false, errUnsafeRewrite
	}
	out := strings.TrimSuffix(buf.String(), "\n")

	// 校验：执行器看到的新工作流必须正好等于预期
	actual, err := decodeExecTree(out)
	if err != nil || !reflect.DeepEqual(expected, actual) {
		return content, false, errUnsafeRewrite
	}
	return out, true, nil
}

// sameDomainSet 比较两个逗号分隔的域名列表是否为同一集合，只忽略顺序和重复项。
// 与运行时匹配（apply.FindMatchedCert → public.ContainsAllIgnoreBRepeats）一致，按原字符串精确比较。
func sameDomainSet(a, b string) bool {
	toSet := func(s string) map[string]bool {
		set := map[string]bool{}
		for _, d := range strings.Split(s, ",") {
			set[d] = true
		}
		return set
	}
	sa, sb := toSet(a), toSet(b)
	if len(sa) != len(sb) {
		return false
	}
	for d := range sa {
		if !sb[d] {
			return false
		}
	}
	return true
}

// GetWorkflowRefs returns workflows associated with a cert identified by its db id and sha256.
func GetWorkflowRefs(id, sha256 string) []map[string]string {
	s, err := GetSqlite()
	if err != nil {
		return []map[string]string{}
	}
	rows, err := s.Where("id=?", []interface{}{id}).Select()
	s.Close()
	if err != nil || len(rows) == 0 {
		return []map[string]string{}
	}
	wfId := fmt.Sprintf("%v", rows[0]["workflow_id"])

	// latest cert per workflow_id (same logic as GetList)
	latestCertForWorkflow := map[string]int64{}
	if sc, e2 := GetSqlite(); e2 == nil {
		if all, e3 := sc.Field([]string{"id", "workflow_id"}).Where("workflow_id != '' AND workflow_id != 'null'", []interface{}{}).Select(); e3 == nil {
			for _, c := range all {
				wfid := fmt.Sprintf("%v", c["workflow_id"])
				if wfid == "" || wfid == "<nil>" {
					continue
				}
				var cid int64
				switch v := c["id"].(type) {
				case int64:
					cid = v
				case int:
					cid = int64(v)
				}
				if prev, ok := latestCertForWorkflow[wfid]; !ok || cid > prev {
					latestCertForWorkflow[wfid] = cid
				}
			}
		}
		sc.Close()
	}
	var certId int64
	switch v := rows[0]["id"].(type) {
	case int64:
		certId = v
	case int:
		certId = int64(v)
	}

	workflows, _ := getWorkflowsBySha256s()
	var refs []map[string]string
	seen := map[string]bool{}
	for _, w := range workflows {
		wid := fmt.Sprintf("%v", w["id"])
		wname, _ := w["name"].(string)
		wcontent, _ := w["content"].(string)
		if seen[wid] {
			continue
		}
		isLatest := wfId != "" && wfId != "<nil>" && wfId == wid && certId == latestCertForWorkflow[wfId]
		if isLatest || (sha256 != "" && strings.Contains(wcontent, sha256)) {
			refs = append(refs, map[string]string{"id": wid, "name": wname})
			seen[wid] = true
		}
	}
	if refs == nil {
		return []map[string]string{}
	}
	return refs
}

func UploadCert(key, cert string) (string, error) {
	sha256, err := SaveCert("upload", key, cert, "", "")
	if err != nil {
		return sha256, fmt.Errorf("保存证书失败: %v", err)
	}
	return sha256, nil
}

func DelCert(id string) error {
	s, err := GetSqlite()
	if err != nil {
		return err
	}
	defer s.Close()

	_, err = s.Where("id in ("+id+")", []interface{}{}).Delete()
	if err != nil {
		return err
	}
	return nil
}

func GetCert(id string) (map[string]string, error) {
	s, err := GetSqlite()
	if err != nil {
		return nil, err
	}
	defer s.Close()

	res, err := s.Where("id=? or sha256=?", []interface{}{id, id}).Select()
	if err != nil {
		return nil, err
	}
	if len(res) == 0 {
		return nil, fmt.Errorf("证书不存在")
	}

	data := map[string]string{
		"domains": res[0]["domains"].(string),
		"cert":    res[0]["cert"].(string),
		"key":     res[0]["key"].(string),
	}

	return data, nil
}

